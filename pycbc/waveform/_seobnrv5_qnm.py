@lru_cache(maxsize=None)
def _qnm_spline(ell, emm):
    """Return GSL-compatible natural-cubic interpolation of the table."""

    try:
        values = _REAL_OMEGA[(ell, emm)]
    except KeyError as exc:
        raise ValueError(f"unsupported SEOBNRv5 QNM mode {(ell, emm)}") from exc
    return NaturalCubicSpline(
        _SPIN_GRID,
        values,
        extrapolate=False,
    )


def seobnrv5_final_mass_spin(mass1, mass2, spin1z, spin2z):
    """Return the SEOBNRv5_ROM remnant mass (solar masses) and spin."""

    # SEOBNRv5_ROM uses the UIB2016 mass fit but retains SEOBNRv4's
    # Barausse+16 final-spin fit.
    _, final_spin = seobnrv4_final_mass_spin(mass1, mass2, spin1z, spin2z)
    final_mass = bbh_final_mass_non_precessing_uib2016(mass1, mass2, spin1z, spin2z)
    return final_mass, final_spin


def fundamental_qnm_omega(final_spin, ell=2, emm=2):
    """Return ``M_final * omega`` for a tabulated v5 fundamental QNM."""

    mode = (ell, abs(emm))
    if mode not in _REAL_OMEGA:
        raise ValueError(f"unsupported SEOBNRv5 QNM mode {ell, emm}")
    interpolation_spin = float(final_spin)
    if not np.isfinite(interpolation_spin):
        raise ValueError("final spin must be finite")

    sign = -1.0 if emm < 0 else 1.0
    interpolation_spin = float(
        np.clip(sign * interpolation_spin, _SPIN_GRID[0], _SPIN_GRID[-1])
    )
    return sign * float(_qnm_spline(*mode)(interpolation_spin))


def seobnrv5_qnm_omega(mass1, mass2, spin1z, spin2z, ell=2, emm=2):
    """Return ``M_total * omega_QNM`` for an SEOBNRv5_ROM remnant."""

    final_mass, final_spin = seobnrv5_final_mass_spin(mass1, mass2, spin1z, spin2z)
    final_mass_omega = fundamental_qnm_omega(final_spin, ell, emm)
    return final_mass_omega * (mass1 + mass2) / final_mass


